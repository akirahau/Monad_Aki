// Khởi tạo Web3
let web3;
let akiContract;
let usdcContract;
let userAddress;

// Kiểm tra và kết nối ví Metamask
async function initWeb3() {
    if (window.ethereum) {
        web3 = new Web3(window.ethereum);
        try {
            // Yêu cầu kết nối ví
            await window.ethereum.request({ method: 'eth_requestAccounts' });
            userAddress = (await web3.eth.getAccounts())[0];
            akiContract = new web3.eth.Contract(akiTokenABI, akiTokenAddress);
            usdcContract = new web3.eth.Contract(usdcABI, usdcAddress);

            // Cập nhật UI sau khi kết nối
            document.getElementById('connect-btn').innerText = 'Connected';
            updateBalances();
        } catch (error) {
            console.error("User denied account access", error);
            alert("Failed to connect wallet. Please try again.");
        }
    } else {
        alert("Please install Metamask to use this app!");
    }
}

// Cập nhật số dư AKI và USDC trên UI
async function updateBalances() {
    try {
        // Số dư AKI
        const akiBalance = await akiContract.methods.balanceOf(userAddress).call();
        const akiBalanceFormatted = web3.utils.fromWei(akiBalance, 'ether'); // AKI có 18 decimals
        document.getElementById('user-balance').innerText = `${parseFloat(akiBalanceFormatted).toFixed(2)} AKI`;

        // Số dư USDC
        const usdcBalance = await usdcContract.methods.balanceOf(userAddress).call();
        const usdcBalanceFormatted = (usdcBalance / 1e6).toFixed(2); // USDC có 6 decimals
        document.getElementById('usdc-balance').innerText = `Balance: ${usdcBalanceFormatted} USDC`;
    } catch (error) {
        console.error("Error updating balances", error);
    }
}

// Xử lý sự kiện khi nhấn nút "Connect"
document.getElementById('connect-btn').addEventListener('click', async () => {
    await initWeb3();
});

// Xử lý sự kiện khi nhấn nút "Mint"
document.getElementById('mint-btn').addEventListener('click', async () => {
    const amount = document.getElementById('mint-amount').value;
    if (!amount || amount <= 0) {
        alert('Please enter a valid amount.');
        return;
    }

    try {
        // Chuyển đổi lượng USDC sang số có 6 decimals
        const usdcAmount = Math.floor(amount * 1e6); // USDC có 6 decimals

        // Approve USDC cho contract AKIToken
        await usdcContract.methods.approve(akiTokenAddress, usdcAmount).send({ from: userAddress });
        alert('USDC approved successfully!');

        // Gọi hàm mintWithUSDC
        await akiContract.methods.mintWithUSDC(usdcAmount).send({ from: userAddress });
        alert(`Successfully minted ${amount} AKI!`);

        // Cập nhật số dư sau khi mint
        await updateBalances();
    } catch (error) {
        console.error("Error during minting", error);
        alert("Minting failed. Check console for details.");
    }
});